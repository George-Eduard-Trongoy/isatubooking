-- Online payment details for room bookings (mock "Sandbox" wallet)
ALTER TABLE public.room_bookings
  ADD COLUMN payment_method text NOT NULL DEFAULT 'pay_at_desk',
  ADD COLUMN payment_status text NOT NULL DEFAULT 'unpaid',
  ADD COLUMN amount_due numeric NOT NULL DEFAULT 0,
  ADD COLUMN payment_reference text,
  ADD COLUMN paid_at timestamptz;

ALTER TABLE public.room_bookings
  ADD CONSTRAINT room_bookings_payment_method_check CHECK (payment_method IN ('pay_at_desk', 'sandbox')),
  ADD CONSTRAINT room_bookings_payment_status_check CHECK (payment_status IN ('unpaid', 'paid', 'refunded'));

UPDATE public.room_bookings rb
SET amount_due = r.price_per_night * GREATEST(1, rb.check_out - rb.check_in)
FROM public.rooms r
WHERE r.id = rb.room_id;

-- Documents each venue requires, with a downloadable soft copy
CREATE TABLE public.venue_document_requirements (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  venue_id integer NOT NULL REFERENCES public.venues(id) ON DELETE CASCADE,
  title text NOT NULL,
  description text NOT NULL DEFAULT '',
  template_path text,
  template_name text,
  sort_order integer NOT NULL DEFAULT 0,
  active boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

GRANT SELECT ON public.venue_document_requirements TO anon, authenticated;
GRANT INSERT, UPDATE ON public.venue_document_requirements TO authenticated;
GRANT USAGE, SELECT ON SEQUENCE public.venue_document_requirements_id_seq TO authenticated;
GRANT ALL ON public.venue_document_requirements TO service_role;

ALTER TABLE public.venue_document_requirements ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Document requirements are public"
  ON public.venue_document_requirements FOR SELECT TO anon, authenticated
  USING (true);

CREATE POLICY "Managers add document requirements"
  ON public.venue_document_requirements FOR INSERT TO authenticated
  WITH CHECK (public.manages_facility(auth.uid(), (SELECT v.facility_id FROM public.venues v WHERE v.id = venue_id)));

CREATE POLICY "Managers update document requirements"
  ON public.venue_document_requirements FOR UPDATE TO authenticated
  USING (public.manages_facility(auth.uid(), (SELECT v.facility_id FROM public.venues v WHERE v.id = venue_id)))
  WITH CHECK (public.manages_facility(auth.uid(), (SELECT v.facility_id FROM public.venues v WHERE v.id = venue_id)));

CREATE INDEX venue_document_requirements_venue_idx ON public.venue_document_requirements (venue_id, sort_order);

-- Photos of completed documents uploaded by clients for a venue booking
CREATE TABLE public.venue_document_submissions (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  booking_id bigint NOT NULL REFERENCES public.venue_bookings(id) ON DELETE CASCADE,
  requirement_id bigint NOT NULL REFERENCES public.venue_document_requirements(id) ON DELETE CASCADE,
  file_paths text[] NOT NULL DEFAULT '{}',
  status text NOT NULL DEFAULT 'pending',
  admin_note text NOT NULL DEFAULT '',
  submitted_by uuid,
  submitted_at timestamptz NOT NULL DEFAULT now(),
  reviewed_by uuid,
  reviewed_at timestamptz,
  CONSTRAINT venue_document_submissions_status_check CHECK (status IN ('pending', 'approved', 'rejected')),
  CONSTRAINT venue_document_submissions_unique UNIQUE (booking_id, requirement_id)
);

GRANT SELECT ON public.venue_document_submissions TO authenticated;
GRANT ALL ON public.venue_document_submissions TO service_role;

ALTER TABLE public.venue_document_submissions ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Owners and managers read document submissions"
  ON public.venue_document_submissions FOR SELECT TO authenticated
  USING (
    EXISTS (
      SELECT 1 FROM public.venue_bookings b
      JOIN public.venues v ON v.id = b.venue_id
      WHERE b.id = booking_id
        AND (b.user_id = auth.uid() OR public.manages_facility(auth.uid(), v.facility_id))
    )
  );

